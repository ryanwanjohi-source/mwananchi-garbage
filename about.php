<p>Mwananchi Garbage is a waste collection company started by Nairobi residents who were tired of irregular collections — trucks that came some weeks and not others, and waste piling up at estate gates. "Mwananchi" means the ordinary citizen, and that is who we work for: households and small businesses that need their waste gone, on a day they can plan around.</p>
<p>We run fixed routes on fixed days. Every customer knows their collection day, every crew follows the same route sheet, and every load is taken to a licensed disposal site or sorted for recycling. If a truck breaks down, a second truck covers the route the same day — the collection still happens.</p>
<h2>What we stand for</h2>
<ul>
<li><strong>On time.</strong> Your collection day does not change from week to week.</li>
<li><strong>Honest pricing.</strong> One monthly price, agreed before we start. No charges at the gate.</li>
<li><strong>Clean finish.</strong> The crew sweeps the bin area before they leave.</li>
<li><strong>Less to landfill.</strong> Paper, plastic, glass and metal are sorted and sent for recycling.</li>
</ul>
